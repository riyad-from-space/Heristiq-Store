/*
 * Turn a folder of photographs into responsive images the site can serve
 * itself, with no image CDN and no third-party account.
 *
 *   node scripts/image-manifest.mjs
 *
 * Runs automatically before `npm run dev` and `npm run build`, so adding a
 * photo is: drop the file in, restart. Nothing to name, register or upload.
 *
 * WHY THIS EXISTS. The site was built around Cloudinary, which resizes and
 * re-encodes on its CDN. That is a good answer, and it is also an account, a
 * bill and a dependency for a shop with seventeen photographs. On Cloudflare
 * Workers everything in public/ is already served from Cloudflare's edge — a
 * real CDN — so the only thing actually missing without Cloudinary is the
 * resizing. This does the resizing at build time instead.
 *
 * Naming: the file's basename is the image id the catalogue refers to, with a
 * dash standing in for the slash. `wc-005--front.jpg` is the id
 * "wc-005/front". A slash cannot appear in a filename, and requiring nested
 * folders for seventeen files would be worse.
 *
 * Resizing uses `sips`, which ships with macOS. On a machine without it — a
 * Linux CI runner — the original is used at every width, which is correct but
 * heavier; the warning says so.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "public/products");
const VARIANTS = path.join(SOURCE, "_r");
const OUT = path.join(ROOT, "src/lib/local-images.generated.ts");

/* Same ladder Cloudinary was asked for, so `sizes` attributes stay correct. */
const WIDTHS = [320, 480, 640, 828, 1080, 1440, 1920];
const EXT = new Set([".jpg", ".jpeg", ".png", ".webp"]);

function have(binary) {
  try {
    execFileSync("which", [binary], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function intrinsicWidth(file) {
  if (!have("sips")) return null;
  try {
    const out = execFileSync("sips", ["-g", "pixelWidth", file], {
      encoding: "utf8",
    });
    const match = out.match(/pixelWidth:\s*(\d+)/);
    return match ? Number(match[1]) : null;
  } catch {
    return null;
  }
}

mkdirSync(SOURCE, { recursive: true });

const sources = readdirSync(SOURCE)
  .filter((name) => EXT.has(path.extname(name).toLowerCase()))
  .sort();

if (sources.length === 0) {
  writeFileSync(
    OUT,
    `/* Generated by scripts/image-manifest.mjs — do not edit.\n` +
      ` * No photographs in public/products/ yet, so every image falls back to\n` +
      ` * Cloudinary if configured, and to the designed placeholder if not. */\n` +
      `export const LOCAL_IMAGES: Record<string, number[]> = {};\n`,
  );
  console.log("  no photographs in public/products/ — manifest is empty");
  process.exit(0);
}

const sips = have("sips");
if (!sips) {
  console.warn(
    "  ! sips not found (macOS only). Originals will be served at every size,\n" +
      "    which works but ships a full-size photo to a phone.",
  );
}

/* Rebuilt from scratch each run, so a deleted photo leaves nothing behind. */
if (existsSync(VARIANTS)) rmSync(VARIANTS, { recursive: true, force: true });
mkdirSync(VARIANTS, { recursive: true });

const manifest = {};

for (const name of sources) {
  const file = path.join(SOURCE, name);
  const base = path.basename(name, path.extname(name));
  /* `wc-005--front` is the id "wc-005/front". */
  const id = base.replace(/--/g, "/");
  const intrinsic = intrinsicWidth(file);
  const sizeKb = Math.round(statSync(file).size / 1024);

  /* Never upscale: a 900px photo gets 320/480/640/828, not 1920. */
  const widths = WIDTHS.filter((w) => !intrinsic || w <= intrinsic);
  if (widths.length === 0) widths.push(WIDTHS[0]);

  const made = [];
  for (const width of widths) {
    const target = path.join(VARIANTS, `${base}-${width}.jpg`);
    if (sips) {
      try {
        execFileSync(
          "sips",
          ["-s", "format", "jpeg", "-s", "formatOptions", "82",
           "-Z", String(width), file, "--out", target],
          { stdio: "ignore" },
        );
        made.push(width);
      } catch {
        /* One bad file must not fail the build. */
      }
    }
  }

  manifest[id] = made.length > 0 ? made : [];
  const note =
    made.length > 0
      ? `${made.length} sizes`
      : `original only (${sizeKb}KB)${intrinsic ? "" : ", size unknown"}`;
  console.log(`  ${id.padEnd(24)} ${note}`);
}

const body = Object.entries(manifest)
  .map(([id, widths]) => `  ${JSON.stringify(id)}: [${widths.join(", ")}],`)
  .join("\n");

writeFileSync(
  OUT,
  `/*\n * Generated by scripts/image-manifest.mjs — do not edit by hand.\n` +
    ` *\n * Maps an image id to the widths available under public/products/_r/.\n` +
    ` * An empty array means only the original exists, so it is served at every\n` +
    ` * size. Regenerated before every dev run and build.\n */\n` +
    `export const LOCAL_IMAGES: Record<string, number[]> = {\n${body}\n};\n`,
);

console.log(`  wrote ${Object.keys(manifest).length} image(s) to the manifest`);
